#!/bin/bash
# ==============================================================================
# Script Name : reportf2b-daily.sh
# Description : Daily HTML defense report generator for Fail2Ban on Zimbra
# Author      : EGTA Software (Ertan Günay)
# Repository  : https://github.com/xertgun/zimbra-fail2ban
# ==============================================================================

# --- Configuration Settings ---
RECIPIENT="admin@yourdomain.com"
SENDER="EGTA Defense System <root@$(hostname -f)>"
SERVER_NAME=$(hostname -f)
LOG_FILE="/var/log/fail2ban.log"

# --- Dynamic Date Parameter Control ---
if [ "$1" == "yesterday" ]; then
    TARGET_DATE=$(date -d "1 day ago" +'%Y-%m-%d')
elif [[ "$1" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]]; then
    TARGET_DATE="$1"
else
    TARGET_DATE=$(date +'%Y-%m-%d')
fi

SUBJECT="[Daily Defense Report] $SERVER_NAME - $TARGET_DATE"

# --- Report Generation ---
(
  echo "To: $RECIPIENT"
  echo "From: $SENDER"
  echo "Subject: $SUBJECT"
  echo "Content-Type: text/html; charset=utf-8"
  echo ""
  echo "<html>"
  echo "<body style='font-family:Ubuntu,Arial,sans-serif;color:#333;margin:0 auto;line-height:1.6;'>"
  echo "  <div style='max-width: 600px; margin: 0 auto; background-color: #ffffff; border-radius: 10px; box-shadow: 0 4px 15px rgba(0,0,0,0.1); overflow: hidden;'>"

  echo "    <div style='background-color: #2c3e50; padding: 25px; color: #ecf0f1; border-radius: 10px 10px 0 0; text-align: center;'>"
  echo "      <h2 style='margin: 0;'>🛡️ EGTA Digital Defense Summary</h2>"
  echo "      <p style='color: wheat;margin: 5px 0;'><b>Server:</b> $SERVER_NAME</p>"
  echo "      <p style='color: yellow;margin: 5px 0;'><b>Date:</b> $TARGET_DATE</p>"
  echo "    </div>"

  echo "    <div style='padding: 30px;'>"

  # --- Section 1: Ban Summary by Jail ---
  echo "      <h3 style='color: #2980b9; border-bottom: 2px solid #2980b9;'>📊 Today's Bans by Jail</h3>"
  echo "      <table style='width: 100%; border-collapse: collapse;'>"
  echo "        <tr style='background-color: #f2f2f2;'><th style='padding: 10px; text-align: left;'>Jail Name</th><th style='padding: 10px; text-align: center;'>Ban Count</th></tr>"
  grep "$TARGET_DATE" $LOG_FILE | grep "fail2ban.actions" | grep " Ban " | grep -oE '\]: [A-Z]+ +\[[^]]+\]' | grep -oE '\[[^]]+\]' | tr -d '[]' | sort | uniq -c | \
  awk '{printf "      <tr><td style=\"padding: 10px; border-bottom: 1px solid #ddd;\"><b>%s</b></td><td style=\"padding: 10px; border-bottom: 1px solid #ddd; text-align: center; color: #c0392b;\"><b>%s</b></td></tr>\n", $2, $1}'
  echo "      </table>"

  # --- Section 2: Hourly Intensity ---
  echo "      <h3 style='color: #27ae60; border-bottom: 2px solid #27ae60; margin-top: 30px;'>⏰ Attack Intensity (Hourly)</h3>"
  echo "      <p style='font-size: 14px;'>Peak attack hours recorded today:</p>"
  echo "      <div style='background-color: #f9f9f9; padding: 10px; border-left: 5px solid #27ae60; font-family: monospace;'>"
  grep "$TARGET_DATE" $LOG_FILE | grep "fail2ban.actions" | grep " Ban " | grep -oE '^[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}' | awk '{print $2}' | sort | uniq -c | \
  awk '{printf "      <span style=\"display:inline-block; margin-right: 15px;\"><strong>%02d:00</strong> (%d)</span>\n", $2, $1}'
  echo "      </div>"

  # --- Section 3: Aggressive Attackers ---
  echo "      <h3 style='color: #e67e22; border-bottom: 2px solid #e67e22; margin-top: 30px;'>🚫 Top 5 Aggressive Attackers</h3>"
  echo "      <ul style='list-style-type: none; padding-left: 0;'>"
  grep "$TARGET_DATE" $LOG_FILE | grep "fail2ban.actions" | grep " Ban " | grep -oE '[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}' | sort | uniq -c | sort -nr | head -n 5 | \
  awk '{printf "      <li style=\"padding: 5px 0; border-bottom: 1px dashed #ccc;\">📍 %s <span style=\"color: #7f8c8d;\">[%s attempts]</span></li>\n", $2, $1}'
  echo "      </table>"

  # --- Section 4: Currently Active Bans ---
  active_ban=$(fail2ban-client status | grep "Jail list:" | sed 's/.*://; s/,//g' | xargs -n1 fail2ban-client status | awk '/Currently banned:/ {sum+=$NF} END {print sum+0}')
  echo "      <div style='margin-top: 30px; background-color: #e74c3c; color: white; padding: 15px; border-radius: 5px; text-align: center;'>"
  echo "        <strong>Currently Active Banned IPs: ${active_ban:-0}</strong> (Enforced across all active jails)"
  echo "      </div>"

  echo "      <p style='margin-top: 20px; font-size: 12px; color: #95a5a6; text-align: center;'>This report was automatically generated by EGTA Defense System.</p>"
  echo "    </div>"
  echo "  </div>"
  echo "</body>"
  echo "</html>"
) | /opt/zimbra/common/sbin/sendmail -t
